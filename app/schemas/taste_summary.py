"""Bounded UI copy and the public API-AI-1 summary contract."""

import unicodedata
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.schemas.taste_profile import TasteProfileSchema

SummaryTypeCode = Literal[
    "CAFE_DESSERT", "CULTURE", "BEACH", "OUTDOOR", "NATURE",
    "FOOD", "SHOPPING", "NIGHTLIFE", "WELLNESS", "EXPERIENCE",
]
# The exact allowed cities are validated against each request's shortlist by
# assemble_taste_summary. Avoid sending the entire catalog in the LLM schema.
CityCode = Annotated[str, Field(min_length=1, max_length=48, pattern=r"^[A-Z]+(?:_[A-Z]+)*$")]


class SummaryModel(BaseModel):
    """Reject extra output fields and blank/oversized strings in derived models."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class SummaryTypeCopy(SummaryModel):
    """Only the title of a server-selected interest is generated by the model."""

    typeCode: SummaryTypeCode = Field(..., description="입력에 제공된 유형 코드")
    typeName: str = Field(..., min_length=1, max_length=24, description="유형 의미를 유지한 맞춤 이름")


class SummaryType(SummaryTypeCopy):
    """An evidence-supported, unipolar interest slider; not a personality test."""

    lowName: str = Field(..., min_length=1, max_length=16, description="관심 신호가 약한 방향")
    highName: str = Field(..., min_length=1, max_length=16, description="관심 신호가 강한 방향")
    score: int = Field(..., strict=True, ge=0, le=100, description="보정 점수의 0~100 표시값, 확률 아님")


class CityRecommendationCopy(SummaryModel):
    """Choose a supplied city by stable identity; do not generate country pairs."""

    cityCode: CityCode = Field(..., description="제공된 추천 후보 중 선택한 도시 코드")
    reason: str = Field(..., min_length=1, max_length=160, description="관측 취향과 도시 특성을 연결한 짧은 이유")


class CityRecommendation(SummaryModel):
    countryName: str = Field(..., min_length=1, max_length=60, description="추천 국가명")
    cityName: str = Field(..., min_length=1, max_length=60, description="추천 도시명")
    reason: str = Field(..., min_length=1, max_length=160, description="추천 이유")


class SummaryCopy(SummaryModel):
    """Compact introduction and 3–4 unique tags shared by draft and response."""

    intro: str = Field(..., min_length=1, max_length=96, description="근거가 있는 여행 취향의 간단한 소개")
    hashtags: list[str] = Field(..., min_length=3, max_length=4, description="짧고 중복 없는 해시태그 3~4개")

    @field_validator("hashtags")
    @classmethod
    def validate_hashtags(cls, values: list[str]) -> list[str]:
        """Normalize tags and enforce a conservative text-width budget.

        Actual pixel fitting remains the frontend's responsibility.
        Raises:
            ValueError: Tags are empty, duplicated, contain punctuation or exceed the budget.
        """
        tags = []
        widths = []
        for value in values:
            body = unicodedata.normalize("NFKC", value).strip().removeprefix("#")
            if not body or not all(char.isalnum() or char == "_" for char in body):
                raise ValueError("hashtags must contain only letters, numbers or underscores")
            tag = "#" + body
            width = sum(2 if unicodedata.east_asian_width(char) in {"W", "F"} else 1 for char in tag)
            if width > 15:
                raise ValueError("hashtag exceeds the short-label budget")
            tags.append(tag)
            widths.append(width)
        if len({tag.casefold() for tag in tags}) != len(tags):
            raise ValueError("hashtags must be unique")
        if sum(widths) + 2 * (len(tags) - 1) > 48:
            raise ValueError("hashtags exceed the combined display budget")
        return tags


class TasteSummaryDraft(SummaryCopy):
    """Internal structured LLM output without editable scores or axis endpoints."""

    types: list[SummaryTypeCopy] = Field(..., max_length=3, description="입력 유형을 각 1회 사용, 입력이 없으면 빈 배열")
    recommendCity: CityRecommendationCopy = Field(..., description="후보 도시와 추천 설명")


class TasteSummary(SummaryCopy):
    types: list[SummaryType] = Field(..., max_length=3, description="근거가 있는 맞춤 유형, 부족하면 0~2개")
    recommendCity: CityRecommendation = Field(..., description="국가·도시·추천 이유")


class BehaviorAnalysisResponse(SummaryModel):
    """The complete SSE event data; internal evidence never enters this object."""

    tasteProfile: TasteProfileSchema = Field(..., description="기존 취향 점수")
    summary: TasteSummary = Field(..., description="화면에 표시할 취향 요약")
